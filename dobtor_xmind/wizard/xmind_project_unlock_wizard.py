# -*- coding: utf-8 -*-
from odoo import models, fields, api, _
from odoo.exceptions import UserError


class XMindProjectUnlockWizard(models.TransientModel):
    """專案管理員解除心智圖的專案鎖（見 xmind.workbook.action_admin_unlock_project）。"""
    _name = 'xmind.project.unlock.wizard'
    _description = 'Unlock Mind Map Project'

    workbook_id = fields.Many2one('xmind.workbook', string='Mind Map', required=True,
                                  ondelete='cascade')
    project_id = fields.Many2one(related='workbook_id.project_id', string='Project')
    policy = fields.Selection([
        ('keep', 'Keep the tasks in the project (only remove the links)'),
        ('archive', 'Archive the tasks generated by the mind map, then remove the links'),
    ], string='Tasks', required=True, default='keep')
    confirm_text = fields.Char(
        'Type the project name to confirm',
        help='Unlocking cannot be undone by the mind map. Type the project name to confirm.')

    def action_confirm(self):
        self.ensure_one()
        expected = (self.project_id.name or '').strip()
        if expected and (self.confirm_text or '').strip() != expected:
            raise UserError(_('Please type the project name "%s" to confirm.', expected))
        self.workbook_id.action_admin_unlock_project(self.policy)
        return {'type': 'ir.actions.act_window_close'}
